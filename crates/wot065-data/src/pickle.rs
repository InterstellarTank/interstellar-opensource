//! Hand-rolled Python-2 protocol-2 pickle codec, plus zlib helpers.
//!
//! The WoT 0.6.5 client is Python 2.6 and applies the account data with
//! `cPickle.loads(zlib.decompress(data))` (`client/SyncController.py:52-56`) and
//! `cPickle.loads(ext)` (`client/Account.py:109-110`, `client/Account.py:208-209`).
//! We therefore emit protocol-2 pickles with Python-2 byte strings (`str`, *not*
//! `unicode`) and genuine Python-2 `set` objects (the client stores the "growing set"
//! stats in `set()` and later does `set |= diff[...]`, which only accepts a set).
//!
//! No Python runtime is required by this crate: the writer below is a complete
//! implementation of the subset of protocol 2 we need. A reader is included for tests
//! and for cross-checking the reference payloads generated by Python 2.7.

use std::collections::BTreeMap;
use std::fmt;

use flate2::read::ZlibDecoder;
use flate2::write::ZlibEncoder;
use flate2::Compression;
use std::io::{Read, Write};

/// A Python value, restricted to the object types that appear in WoT 0.6.5 account
/// payloads. Byte strings are kept as raw bytes because Python-2 `str` is bytes
/// (the client unpacks them with `struct`).
///
/// Equality is *semantic*: dicts and sets are compared order-insensitively, so a value
/// built by our writer can be compared with a value parsed from a Python-generated
/// reference pickle.
#[derive(Debug, Clone)]
pub enum Value {
    None,
    Bool(bool),
    Int(i64),
    Float(f64),
    /// Python-2 `str` (bytes).
    Str(Vec<u8>),
    List(Vec<Value>),
    Tuple(Vec<Value>),
    Dict(Vec<(Value, Value)>),
    Set(Vec<Value>),
}

impl Value {
    pub fn str(s: impl Into<Vec<u8>>) -> Value {
        Value::Str(s.into())
    }

    pub fn list(items: Vec<Value>) -> Value {
        Value::List(items)
    }

    pub fn tuple(items: Vec<Value>) -> Value {
        Value::Tuple(items)
    }

    pub fn dict(items: Vec<(Value, Value)>) -> Value {
        Value::Dict(items)
    }

    pub fn set(items: Vec<Value>) -> Value {
        Value::Set(items)
    }

    /// Convenience for a dict with `&str` keys.
    pub fn sd(items: Vec<(&str, Value)>) -> Value {
        Value::Dict(
            items
                .into_iter()
                .map(|(k, v)| (Value::str(k), v))
                .collect(),
        )
    }

    pub fn get(&self, key: &str) -> Option<&Value> {
        match self {
            Value::Dict(pairs) => pairs
                .iter()
                .find(|(k, _)| k.as_bytes() == Some(key.as_bytes()))
                .map(|(_, v)| v),
            _ => None,
        }
    }

    pub fn contains(&self, key: &str) -> bool {
        self.get(key).is_some()
    }

    pub fn as_bytes(&self) -> Option<&[u8]> {
        match self {
            Value::Str(b) => Some(b),
            _ => None,
        }
    }

    pub fn as_int(&self) -> Option<i64> {
        match self {
            Value::Int(i) => Some(*i),
            Value::Bool(b) => Some(*b as i64),
            _ => None,
        }
    }

    pub fn as_float(&self) -> Option<f64> {
        match self {
            Value::Float(f) => Some(*f),
            Value::Int(i) => Some(*i as f64),
            _ => None,
        }
    }

    pub fn as_list(&self) -> Option<&[Value]> {
        match self {
            Value::List(v) | Value::Tuple(v) => Some(v),
            _ => None,
        }
    }

    pub fn as_dict(&self) -> Option<&[(Value, Value)]> {
        match self {
            Value::Dict(v) => Some(v),
            _ => None,
        }
    }

    pub fn as_set(&self) -> Option<&[Value]> {
        match self {
            Value::Set(v) => Some(v),
            _ => None,
        }
    }
}

impl PartialEq for Value {
    fn eq(&self, other: &Self) -> bool {
        match (self, other) {
            (Value::None, Value::None) => true,
            (Value::Bool(a), Value::Bool(b)) => a == b,
            (Value::Int(a), Value::Int(b)) => a == b,
            // Python: True == 1, so tolerate the int/bool overlap when comparing trees.
            (Value::Bool(a), Value::Int(b)) | (Value::Int(b), Value::Bool(a)) => *a as i64 == *b,
            (Value::Float(a), Value::Float(b)) => a == b,
            (Value::Float(a), Value::Int(b)) | (Value::Int(b), Value::Float(a)) => *a == *b as f64,
            (Value::Str(a), Value::Str(b)) => a == b,
            (Value::List(a), Value::List(b)) | (Value::Tuple(a), Value::Tuple(b)) => a == b,
            (Value::List(a), Value::Tuple(b)) | (Value::Tuple(a), Value::List(b)) => a == b,
            (Value::Dict(a), Value::Dict(b)) => unordered_eq(a, b),
            (Value::Set(a), Value::Set(b))
            | (Value::Set(a), Value::List(b))
            | (Value::List(a), Value::Set(b)) => set_eq(a, b),
            _ => false,
        }
    }
}

/// Order-insensitive set equality (duplicates are not expected in our payloads).
fn set_eq(a: &[Value], b: &[Value]) -> bool {
    if a.len() != b.len() {
        return false;
    }
    let mut used = vec![false; b.len()];
    'outer: for x in a {
        for (i, y) in b.iter().enumerate() {
            if !used[i] && x == y {
                used[i] = true;
                continue 'outer;
            }
        }
        return false;
    }
    true
}

/// Order-insensitive multiset equality for dict pairs.
fn unordered_eq(a: &[(Value, Value)], b: &[(Value, Value)]) -> bool {
    if a.len() != b.len() {
        return false;
    }
    let mut used = vec![false; b.len()];
    'outer: for (ka, va) in a {
        for (i, (kb, vb)) in b.iter().enumerate() {
            if !used[i] && ka == kb && va == vb {
                used[i] = true;
                continue 'outer;
            }
        }
        return false;
    }
    true
}

impl Value {
    /// Look up an integer key in a dict (inventory item-type keys are ints).
    pub fn get_int(&self, key: i64) -> Option<&Value> {
        match self {
            Value::Dict(pairs) => pairs
                .iter()
                .find(|(k, _)| k.as_int() == Some(key))
                .map(|(_, v)| v),
            _ => None,
        }
    }

    /// Look up a byte-string key in a dict.
    pub fn get_bytes(&self, key: &[u8]) -> Option<&Value> {
        match self {
            Value::Dict(pairs) => pairs
                .iter()
                .find(|(k, _)| k.as_bytes() == Some(key))
                .map(|(_, v)| v),
            _ => None,
        }
    }
}

/// Error produced while reading a pickle.
#[derive(Debug, Clone)]
pub struct PickleError(pub String);

impl fmt::Display for PickleError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "pickle error: {}", self.0)
    }
}

impl std::error::Error for PickleError {}

