enum StackItem {
    Value(Value),
    Mark,
    Global(String, String),
}

/// Memo entries can hold either a plain value or a (not-yet-reduced) global reference.
#[derive(Clone)]
enum MemoEntry {
    Value(Value),
    Global(String, String),
}

/// Parse a protocol-2 pickle into a [`Value`].
pub fn loads(data: &[u8]) -> Result<Value, PickleError> {
    let mut r = PickleReader {
        data,
        pos: 0,
        stack: Vec::new(),
        memo: BTreeMap::new(),
    };
    r.read_all()
}

struct PickleReader<'a> {
    data: &'a [u8],
    pos: usize,
    stack: Vec<StackItem>,
    // Memo indices come from the stream and can be sparse.
    memo: BTreeMap<usize, MemoEntry>,
}

impl<'a> PickleReader<'a> {
    fn err<T>(&self, msg: &str) -> Result<T, PickleError> {
        Err(PickleError(format!(
            "{} at offset {} (opcode {:#04x})",
            msg,
            self.pos,
            self.data.get(self.pos).copied().unwrap_or(0)
        )))
    }

    fn u8(&mut self) -> Result<u8, PickleError> {
        let b = *self.data.get(self.pos).ok_or(PickleError("eof".into()))?;
        self.pos += 1;
        Ok(b)
    }

    fn take(&mut self, n: usize) -> Result<&'a [u8], PickleError> {
        if self.pos + n > self.data.len() {
            return self.err("unexpected eof");
        }
        let s = &self.data[self.pos..self.pos + n];
        self.pos += n;
        Ok(s)
    }

    fn read_line(&mut self) -> Result<String, PickleError> {
        let start = self.pos;
        while self.pos < self.data.len() && self.data[self.pos] != b'\n' {
            self.pos += 1;
        }
        if self.pos >= self.data.len() {
            return self.err("eof in line");
        }
        let s = String::from_utf8_lossy(&self.data[start..self.pos]).into_owned();
        self.pos += 1;
        Ok(s)
    }

    fn push(&mut self, v: Value) {
        self.stack.push(StackItem::Value(v));
    }

    fn pop(&mut self) -> Result<Value, PickleError> {
        match self.stack.pop() {
            Some(StackItem::Value(v)) => Ok(v),
            _ => self.err("expected value on stack"),
        }
    }

    /// Drain values after the latest MARK (which is removed) and return them.
    fn pop_mark_items(&mut self) -> Result<Vec<Value>, PickleError> {
        let mark = self
            .stack
            .iter()
            .rposition(|i| matches!(i, StackItem::Mark))
            .ok_or_else(|| PickleError("mark not found".into()))?;
        let tail = self.stack.split_off(mark + 1);
        self.stack.pop(); // the mark
        let mut items = Vec::with_capacity(tail.len());
        for item in tail {
            match item {
                StackItem::Value(v) => items.push(v),
                _ => return self.err("non-value after mark"),
            }
        }
        Ok(items)
    }

    fn read_all(&mut self) -> Result<Value, PickleError> {
        loop {
            if self.pos >= self.data.len() {
                return self.err("eof before STOP");
            }
            let op = self.u8()?;
            match op {
                0x80 => {
                    let proto = self.u8()?;
                    if proto > 2 {
                        return Err(PickleError(format!("unsupported protocol {proto}")));
                    }
                }
                b'.' => {
                    // STOP
                    return match self.stack.pop() {
                        Some(StackItem::Value(v)) => Ok(v),
                        _ => self.err("stop with empty/invalid stack"),
                    };
                }
                b'N' => self.push(Value::None),
                0x88 => self.push(Value::Bool(true)),
                0x89 => self.push(Value::Bool(false)),
                b'(' => self.stack.push(StackItem::Mark),
                b'K' => {
                    let v = self.u8()?;
                    self.push(Value::Int(v as i64));
                }
                b'M' => {
                    let v = self.take(2)?;
                    self.push(Value::Int(u16::from_le_bytes([v[0], v[1]]) as i64));
                }
                b'J' => {
                    let v = self.take(4)?;
                    self.push(Value::Int(i32::from_le_bytes([v[0], v[1], v[2], v[3]]) as i64));
                }
                b'I' => {
                    let line = self.read_line()?;
                    let v: i64 = line
                        .trim()
                        .parse()
                        .map_err(|_| PickleError(format!("bad INT {line:?}")))?;
                    self.push(Value::Int(v));
                }
                b'L' => {
                    let mut line = self.read_line()?;
                    if line.ends_with('L') {
                        line.pop();
                    }
                    let v: i64 = line
                        .trim()
                        .parse()
                        .map_err(|_| PickleError(format!("bad LONG {line:?}")))?;
                    self.push(Value::Int(v));
                }
                0x8a => {
                    // LONG1: 1-byte length, little-endian two's complement
                    let n = self.u8()? as usize;
                    let raw = self.take(n)?;
                    let mut buf = [0u8; 8];
                    let sign = raw.last().map(|b| b & 0x80 != 0).unwrap_or(false);
                    if raw.len() > 8 {
                        return self.err("LONG1 too big");
                    }
                    buf[..raw.len()].copy_from_slice(raw);
                    if sign {
                        for b in &mut buf[raw.len()..] {
                            *b = 0xff;
                        }
                    }
                    self.push(Value::Int(i64::from_le_bytes(buf)));
                }
                b'G' => {
                    let raw = self.take(8)?;
                    let mut a = [0u8; 8];
                    a.copy_from_slice(raw);
                    self.push(Value::Float(f64::from_be_bytes(a)));
                }
                b'F' => {
                    let line = self.read_line()?;
                    let v: f64 = line
                        .trim()
                        .parse()
                        .map_err(|_| PickleError(format!("bad FLOAT {line:?}")))?;
                    self.push(Value::Float(v));
                }
                b'U' => {
                    let n = self.u8()? as usize;
                    let raw = self.take(n)?;
                    self.push(Value::Str(raw.to_vec()));
                }
                b'T' => {
                    let n = self.take(4)?;
                    let n = u32::from_le_bytes([n[0], n[1], n[2], n[3]]) as usize;
                    let raw = self.take(n)?;
                    self.push(Value::Str(raw.to_vec()));
                }
                b'S' => {
                    let line = self.read_line()?;
                    self.push(Value::Str(parse_repr_string(&line)?));
                }
                b'V' => {
                    let line = self.read_line()?;
                    self.push(Value::Str(line.into_bytes()));
                }
                b'X' => {
                    let n = self.take(4)?;
                    let n = u32::from_le_bytes([n[0], n[1], n[2], n[3]]) as usize;
                    let raw = self.take(n)?;
                    self.push(Value::Str(raw.to_vec()));
                }
                b']' => self.push(Value::List(Vec::new())),
                b'l' => {
                    let items = self.pop_mark_items()?;
                    self.push(Value::List(items));
                }
                b'e' => {
                    let items = self.pop_mark_items()?;
                    let mut list = self.pop()?;
                    match &mut list {
                        Value::List(v) => v.extend(items),
                        _ => return self.err("APPENDS on non-list"),
                    }
                    self.push(list);
                }
                b'a' => {
                    let item = self.pop()?;
                    let mut list = self.pop()?;
                    match &mut list {
                        Value::List(v) => v.push(item),
                        _ => return self.err("APPEND on non-list"),
                    }
                    self.push(list);
                }
                b')' => self.push(Value::Tuple(Vec::new())),
                b't' => {
                    let items = self.pop_mark_items()?;
                    self.push(Value::Tuple(items));
                }
                0x85 => {
                    let a = self.pop()?;
                    self.push(Value::Tuple(vec![a]));
                }
                0x86 => {
                    let b = self.pop()?;
                    let a = self.pop()?;
                    self.push(Value::Tuple(vec![a, b]));
                }
                0x87 => {
                    let c = self.pop()?;
                    let b = self.pop()?;
                    let a = self.pop()?;
                    self.push(Value::Tuple(vec![a, b, c]));
                }
                b'}' => self.push(Value::Dict(Vec::new())),
                b'd' => {
                    let items = self.pop_mark_items()?;
                    if items.len() % 2 != 0 {
                        return self.err("DICT with odd item count");
                    }
                    let mut pairs = Vec::with_capacity(items.len() / 2);
                    let mut it = items.into_iter();
                    while let (Some(k), Some(v)) = (it.next(), it.next()) {
                        pairs.push((k, v));
                    }
                    self.push(Value::Dict(pairs));
                }
                b'u' => {
                    let items = self.pop_mark_items()?;
                    if items.len() % 2 != 0 {
                        return self.err("SETITEMS with odd item count");
                    }
                    let mut dict = self.pop()?;
                    match &mut dict {
                        Value::Dict(pairs) => {
                            let mut it = items.into_iter();
                            while let (Some(k), Some(v)) = (it.next(), it.next()) {
                                pairs.push((k, v));
                            }
                        }
                        _ => return self.err("SETITEMS on non-dict"),
                    }
                    self.push(dict);
                }
                b's' => {
                    let v = self.pop()?;
                    let k = self.pop()?;
                    let mut dict = self.pop()?;
                    match &mut dict {
                        Value::Dict(pairs) => pairs.push((k, v)),
                        _ => return self.err("SETITEM on non-dict"),
                    }
                    self.push(dict);
                }
                0x8f => self.push(Value::Set(Vec::new())),
                0x90 => {
                    let items = self.pop_mark_items()?;
                    let mut set = self.pop()?;
                    match &mut set {
                        Value::Set(v) => v.extend(items),
                        _ => return self.err("ADDITEMS on non-set"),
                    }
                    self.push(set);
                }
                0x91 => {
                    let items = self.pop_mark_items()?;
                    self.push(Value::Set(items));
                }
                b'q' => {
                    // BINPUT: store the stack top in the memo; the stack is NOT popped.
                    let idx = self.u8()? as usize;
                    let v = self.memo_top("BINPUT")?;
                    self.memo.insert(idx, v);
                }
                b'r' => {
                    let raw = self.take(4)?;
                    let idx = u32::from_le_bytes([raw[0], raw[1], raw[2], raw[3]]) as usize;
                    let v = self.memo_top("LONG_BINPUT")?;
                    self.memo.insert(idx, v);
                }
                b'p' => {
                    let line = self.read_line()?;
                    let idx: usize = line
                        .trim()
                        .parse()
                        .map_err(|_| PickleError(format!("bad PUT {line:?}")))?;
                    let v = self.memo_top("PUT")?;
                    self.memo.insert(idx, v);
                }
                b'h' => {
                    let idx = self.u8()? as usize;
                    self.stack.push(self.memo_get(idx)?);
                }
                b'j' => {
                    let raw = self.take(4)?;
                    let idx = u32::from_le_bytes([raw[0], raw[1], raw[2], raw[3]]) as usize;
                    self.stack.push(self.memo_get(idx)?);
                }
                b'g' => {
                    let line = self.read_line()?;
                    let idx: usize = line
                        .trim()
                        .parse()
                        .map_err(|_| PickleError(format!("bad GET {line:?}")))?;
                    self.stack.push(self.memo_get(idx)?);
                }
                b'c' => {
                    let module = self.read_line()?;
                    let name = self.read_line()?;
                    self.stack.push(StackItem::Global(module, name));
                }
                b'R' => {
                    let args = self.pop()?;
                    let global = match self.stack.pop() {
                        Some(StackItem::Global(m, n)) => (m, n),
                        _ => return self.err("REDUCE without GLOBAL"),
                    };
                    let value = match (global.0.as_str(), global.1.as_str()) {
                        ("__builtin__", "set") | ("builtins", "set") => {
                            let items = match args {
                                Value::Tuple(mut a) if a.len() == 1 => match a.pop() {
                                    Some(Value::List(items)) | Some(Value::Set(items)) => items,
                                    _ => return self.err("set() with non-list arg"),
                                },
                                Value::Tuple(a) if a.is_empty() => Vec::new(),
                                _ => return self.err("set() with unexpected args"),
                            };
                            Value::Set(items)
                        }
                        (m, n) => {
                            return Err(PickleError(format!("unsupported GLOBAL {m}.{n}")));
                        }
                    };
                    self.push(value);
                }
                other => {
                    return Err(PickleError(format!(
                        "unsupported opcode {:#04x} at offset {}",
                        other,
                        self.pos - 1
                    )));
                }
            }
        }
    }

    fn memo_top(&self, opcode: &str) -> Result<MemoEntry, PickleError> {
        match self.stack.last() {
            Some(StackItem::Value(v)) => Ok(MemoEntry::Value(v.clone())),
            Some(StackItem::Global(m, n)) => Ok(MemoEntry::Global(m.clone(), n.clone())),
            _ => Err(PickleError(format!(
                "{opcode} with empty stack at offset {}",
                self.pos
            ))),
        }
    }

    fn memo_get(&self, idx: usize) -> Result<StackItem, PickleError> {
        match self
            .memo
            .get(&idx)
            .cloned()
            .ok_or_else(|| PickleError(format!("memo index {idx} missing")))?
        {
            MemoEntry::Value(v) => Ok(StackItem::Value(v)),
            MemoEntry::Global(m, n) => Ok(StackItem::Global(m, n)),
        }
    }
}

fn parse_repr_string(line: &str) -> Result<Vec<u8>, PickleError> {
    // Only the simple `'....'` / `"...."` forms produced by protocol <=2 STRING opcodes.
    let bytes = line.as_bytes();
    if bytes.len() < 2 {
        return Err(PickleError(format!("bad STRING {line:?}")));
    }
    let quote = bytes[0];
    if (quote != b'\'' && quote != b'"') || *bytes.last().unwrap() != quote {
        return Err(PickleError(format!("bad STRING {line:?}")));
    }
    let mut out = Vec::with_capacity(bytes.len() - 2);
    let mut i = 1;
    while i < bytes.len() - 1 {
        let b = bytes[i];
        if b == b'\\' && i + 1 < bytes.len() - 1 {
            i += 1;
            let e = bytes[i];
            out.push(match e {
                b'n' => b'\n',
                b'r' => b'\r',
                b't' => b'\t',
                b'0' => 0,
                b'\\' => b'\\',
                b'\'' => b'\'',
                b'"' => b'"',
                b'x' => {
                    if i + 2 < bytes.len() - 1 {
                        let hex = &line[i + 1..i + 3];
                        let v = u8::from_str_radix(hex, 16).unwrap_or(0);
                        i += 2;
                        v
                    } else {
                        return Err(PickleError(format!("bad hex escape {line:?}")));
                    }
                }
                other => other,
            });
        } else {
            out.push(b);
        }
        i += 1;
    }
    Ok(out)
}

