/// Serialize a value as a Python protocol-2 pickle (Python 2.6 compatible).
pub fn dumps(value: &Value) -> Vec<u8> {
    let mut w = PickleWriter { out: Vec::new() };
    w.out.extend_from_slice(b"\x80\x02"); // PROTO 2
    w.write_value(value);
    w.out.push(b'.'); // STOP
    w.out
}

struct PickleWriter {
    out: Vec<u8>,
}

impl PickleWriter {
    fn write_value(&mut self, value: &Value) {
        match value {
            Value::None => self.out.push(b'N'),
            Value::Bool(true) => self.out.push(0x88), // NEWTRUE
            Value::Bool(false) => self.out.push(0x89), // NEWFALSE
            Value::Int(i) => self.write_int(*i),
            Value::Float(f) => {
                self.out.push(b'G'); // BINFLOAT, big-endian f64
                self.out.extend_from_slice(&f.to_be_bytes());
            }
            Value::Str(bytes) => self.write_str(bytes),
            Value::List(items) => {
                self.out.push(b']'); // EMPTY_LIST
                if !items.is_empty() {
                    self.out.push(b'('); // MARK
                    for item in items {
                        self.write_value(item);
                    }
                    self.out.push(b'e'); // APPENDS
                }
            }
            Value::Tuple(items) => match items.len() {
                0 => self.out.push(b')'), // EMPTY_TUPLE
                1 => {
                    self.write_value(&items[0]);
                    self.out.push(0x85); // TUPLE1
                }
                2 => {
                    self.write_value(&items[0]);
                    self.write_value(&items[1]);
                    self.out.push(0x86); // TUPLE2
                }
                3 => {
                    self.write_value(&items[0]);
                    self.write_value(&items[1]);
                    self.write_value(&items[2]);
                    self.out.push(0x87); // TUPLE3
                }
                _ => {
                    self.out.push(b'('); // MARK
                    for item in items {
                        self.write_value(item);
                    }
                    self.out.push(b't'); // TUPLE
                }
            },
            Value::Dict(pairs) => {
                self.out.push(b'}'); // EMPTY_DICT
                if !pairs.is_empty() {
                    self.out.push(b'('); // MARK
                    for (k, v) in pairs {
                        self.write_value(k);
                        self.write_value(v);
                    }
                    self.out.push(b'u'); // SETITEMS
                }
            }
            Value::Set(items) => {
                // c__builtin__\nset\n ] (items) e  TUPLE1 R  ->  set([...])
                self.out.extend_from_slice(b"c__builtin__\nset\n");
                self.out.push(b']'); // EMPTY_LIST
                if !items.is_empty() {
                    self.out.push(b'('); // MARK
                    for item in items {
                        self.write_value(item);
                    }
                    self.out.push(b'e'); // APPENDS
                }
                self.out.push(0x85); // TUPLE1
                self.out.push(b'R'); // REDUCE
            }
        }
    }

    fn write_int(&mut self, v: i64) {
        if v >= 0 && v <= 0xff {
            self.out.push(b'K'); // BININT1
            self.out.push(v as u8);
        } else if v >= 0 && v <= 0xffff {
            self.out.push(b'M'); // BININT2
            self.out.extend_from_slice(&(v as u16).to_le_bytes());
        } else if v >= i32::MIN as i64 && v <= i32::MAX as i64 {
            self.out.push(b'J'); // BININT
            self.out.extend_from_slice(&(v as i32).to_le_bytes());
        } else {
            // LONG1: signed little-endian two's complement, minimal length; a leading
            // zero byte is needed when the highest bit of the magnitude would read as
            // the sign bit.
            let mut le = v.to_le_bytes().to_vec();
            while le.len() > 1
                && le.last() == Some(&0)
                && (le[le.len() - 2] & 0x80) == 0
            {
                le.pop();
            }
            while le.len() > 1
                && le.last() == Some(&0xff)
                && (le[le.len() - 2] & 0x80) != 0
            {
                le.pop();
            }
            self.out.push(0x8a); // LONG1
            self.out.push(le.len() as u8);
            self.out.extend_from_slice(&le);
        }
    }

    fn write_str(&mut self, bytes: &[u8]) {
        if bytes.len() < 256 {
            self.out.push(b'U'); // SHORT_BINSTRING
            self.out.push(bytes.len() as u8);
        } else {
            self.out.push(b'T'); // BINSTRING
            self.out
                .extend_from_slice(&(bytes.len() as u32).to_le_bytes());
        }
        self.out.extend_from_slice(bytes);
    }
}

